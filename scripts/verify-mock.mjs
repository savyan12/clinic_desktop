import { createServer } from 'vite'

const storage = new Map()
globalThis.localStorage = {
  getItem: (key) => storage.get(key) ?? null,
  setItem: (key, value) => storage.set(key, value),
  removeItem: (key) => storage.delete(key),
}

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' })
const { mockRequest } = await server.ssrLoadModule('/src/mocks/handlers.js')

let token = null
const call = (method, url, data = undefined, params = undefined) => mockRequest({
  method,
  url,
  data,
  params,
  headers: token ? { Authorization: `Bearer ${token}` } : {},
})

const assert = (condition, message) => {
  if (!condition) throw new Error(message)
}

const expectStatus = async (status, action, label) => {
  try {
    await action()
    throw new Error(`${label}: expected HTTP ${status}`)
  } catch (error) {
    if (error.status !== status) throw error
  }
}

try {
  const receptionLogin = await call('POST', '/auth/login', { username: 'reception', password: 'demo' })
  token = receptionLogin.data.token
  localStorage.setItem('clinic-auth', JSON.stringify(receptionLogin.data))
  assert(receptionLogin.data.user.role === 'receptionist', 'Receptionist login failed')
  await expectStatus(403, () => call('GET', '/expenses'), 'Receptionist expense access denial')

  await expectStatus(422, () => call('POST', '/patients', {
    name: 'سجل مكرر للاختبار', phone: '0912345678', age: 30, gender: 'male', area: 'طرابلس', confirm_duplicate: false,
  }), 'Duplicate phone warning')

  const patientResponse = await call('POST', '/patients', {
    name: 'مريض اختبار الواجهة', phone: '0910000029', age: 32, gender: 'male', area: 'طرابلس', confirm_duplicate: false,
  })
  const patient = patientResponse.data

  const subscriptionResponse = await call('POST', '/subscriptions', {
    patient_id: patient.id,
    name: 'برنامج اختبار الاشتراكات',
    service_ids: [1, 2],
    sessions_count: 3,
    total_price: '300.000',
    paid_amount: '100.000',
    method: 'cash',
  })
  const subscription = subscriptionResponse.data.subscription
  assert(subscription.remaining === 3, 'Subscription creation did not preserve remaining sessions')
  assert(subscription.start_date === new Date().toISOString().slice(0, 10), 'Subscription start date was not generated by the backend')
  assert(subscription.total_price === '300.000', 'Subscription price was not preserved as a manual contract value')

  const subscriptionSessionResponse = await call('POST', '/sessions', {
    patient_id: patient.id, doctor_id: 1, type: 'subscription', subscription_id: subscription.id,
    session_date: new Date().toISOString().slice(0, 10),
    services: [{ service_id: 1 }, { service_id: 2 }],
  })
  const subscriptionSession = subscriptionSessionResponse.data.session
  assert(subscriptionSession.status === 'closed', 'Subscription session was not closed during creation')
  assert(subscriptionSession.net_total === '0.000' && subscriptionSession.commission_amount === null, 'Subscription session created financial value or commission')
  assert(subscriptionSessionResponse.data.effects.payment === null, 'Subscription creation created a cash payment')
  const sessionsByNumber = await call('GET', '/sessions', undefined, { search: subscriptionSession.code.replace(/^S-/, '') })
  assert(sessionsByNumber.data.length === 1 && sessionsByNumber.data[0].id === subscriptionSession.id, 'Session number search did not find the matching session')
  await expectStatus(403, () => call('PATCH', `/sessions/${subscriptionSession.id}`, {
    service_ids: [1, 2, 3],
  }), 'Closed subscription service mutation rejection')
  const repeatedClose = await call('POST', `/sessions/${subscriptionSession.id}/close`, {})
  assert(repeatedClose.data.replayed === true, 'Repeated close was not idempotent')
  await expectStatus(422, () => call('POST', `/sessions/${subscriptionSession.id}/services`, {
    services: [{ service_id: 3, item_type: 'service', extra_units: 0 }],
  }), 'Subscription service addition rejection')

  const cashSessionResponse = await call('POST', '/sessions', {
    patient_id: patient.id, doctor_id: 1, type: 'individual', service_ids: [1], discount: '0.000',
    settlement: { coverage: 'cash', wallet_amount: '0.000', paid_amount: '80.000', debt_amount: '0.000', method: 'cash', sponsor_id: null },
  })
  const cashSession = cashSessionResponse.data.session
  assert(cashSessionResponse.data.effects.payment?.amount === '80.000', 'Cash session did not create the expected payment')
  const cashAddition = await call('POST', `/sessions/${cashSession.id}/services`, {
    services: [{ service_id: 2, item_type: 'service', extra_units: 0 }],
    settlement: { wallet_amount: '0.000', paid_amount: '45.000', debt_amount: '0.000', method: 'cash', sponsor_id: null },
  })
  assert(cashAddition.data.session.net_total === '125.000', 'Individual service addition did not update the session total')
  assert(cashAddition.data.effects.payment?.amount === '45.000', 'Individual service addition did not preserve payment behavior')

  await expectStatus(422, () => call('POST', '/sessions', {
    patient_id: patient.id, doctor_id: 2, type: 'individual', service_ids: [3], discount: '0.000',
    settlement: { coverage: 'wallet', wallet_amount: '65.000', paid_amount: '0.000', debt_amount: '0.000', method: 'cash', sponsor_id: null },
  }), 'Insufficient wallet')

  await call('POST', `/patients/${patient.id}/wallet/topups`, { amount: '100.000', method: 'cash' })
  const walletSessionResponse = await call('POST', '/sessions', {
    patient_id: patient.id, doctor_id: 2, type: 'individual', service_ids: [3], discount: '0.000',
    settlement: { coverage: 'wallet', wallet_amount: '65.000', paid_amount: '0.000', debt_amount: '0.000', method: 'cash', sponsor_id: null },
  })
  assert(walletSessionResponse.data.effects.wallet_transaction?.amount === '-65.000', 'Wallet session did not create the debit')

  const debtSessionResponse = await call('POST', '/sessions', {
    patient_id: patient.id, doctor_id: 3, type: 'individual', service_ids: [2], discount: '0.000',
    settlement: { coverage: 'debt', wallet_amount: '0.000', paid_amount: '0.000', debt_amount: '45.000', method: 'cash', sponsor_id: 1 },
  })
  assert(debtSessionResponse.data.effects.debt?.amount === '45.000', 'Debt session did not create the debt')

  const mixedSessionResponse = await call('POST', '/sessions', {
    patient_id: patient.id, doctor_id: 3, type: 'individual', service_ids: [3], discount: '0.000',
    settlement: { coverage: 'mixed', wallet_amount: '20.000', paid_amount: '20.000', debt_amount: '25.000', method: 'transfer', sponsor_id: 1 },
  })
  assert(mixedSessionResponse.data.effects.payment && mixedSessionResponse.data.effects.wallet_transaction && mixedSessionResponse.data.effects.debt, 'Mixed session did not create all three effects')

  await expectStatus(403, () => call('PATCH', `/sessions/${cashSession.id}`, { doctor_id: 2 }), 'Receptionist closed-session edit denial')

  const patientDetails = (await call('GET', `/patients/${patient.id}`)).data
  const openDebts = patientDetails.debts.filter((debt) => ['open', 'partial'].includes(debt.status))
  assert(openDebts.length > 0, 'Expected debts were not visible in patient account')
  const subscriptionDebt = openDebts.find((debt) => debt.subscription_id === subscription.id)
  assert(subscriptionDebt, 'Subscription debt was not created')
  const allocationAmount = Math.min(30, Number(subscriptionDebt.remaining)).toFixed(3)
  await call('POST', '/debts/settlements', {
    amount: allocationAmount,
    method: 'cash',
    allocations: [{ debt_id: subscriptionDebt.id, amount: allocationAmount }],
  })
  await expectStatus(422, () => call('POST', '/debts/settlements', {
    amount: '9999.000', method: 'cash', allocations: [{ debt_id: subscriptionDebt.id, amount: '9999.000' }],
  }), 'Debt over-allocation')

  const adminLogin = await call('POST', '/auth/login', { username: 'admin', password: 'demo' })
  token = adminLogin.data.token
  localStorage.setItem('clinic-auth', JSON.stringify(adminLogin.data))
  assert(adminLogin.data.user.role === 'admin', 'Admin login failed')

  const expenseDate = new Date().toISOString().slice(0, 10)
  const expenseMonth = expenseDate.slice(0, 7)
  await expectStatus(422, () => call('POST', '/expenses', {
    type: 'rent', description: 'إيجار اختبار', payment_date: expenseDate,
    amount: '1000.000', payment_method: 'transfer', rent_month: expenseMonth,
    rent_start_date: expenseDate, rent_end_date: '',
  }), 'Rent date validation')
  const purchaseExpense = (await call('POST', '/expenses', {
    type: 'purchase', description: 'مستلزمات اختبار', recipient: 'المورد', payment_date: expenseDate,
    amount: '120.000', payment_method: 'cash', reference_number: 'MANUAL-NOT-ALLOWED',
  })).data
  assert(/^EXP-\d{8}(?:-\d+)?$/.test(purchaseExpense.reference_number), 'Expense reference was not generated internally')
  assert(purchaseExpense.reference_number !== 'MANUAL-NOT-ALLOWED', 'Client-provided expense reference was accepted')
  const rentExpense = (await call('POST', '/expenses', {
    type: 'rent', description: 'إيجار اختبار', recipient: 'اسم يجب تجاهله', payment_date: expenseDate,
    amount: '1000.000', payment_method: 'transfer', rent_month: expenseMonth,
    rent_start_date: expenseDate, rent_end_date: expenseDate,
  })).data
  assert(rentExpense.recipient === 'صاحب العقار', 'Rent recipient was not assigned internally')
  await expectStatus(422, () => call('POST', `/expenses/${purchaseExpense.id}/correct`, {
    ...purchaseExpense, amount: '125.000', reason: '',
  }), 'Expense correction reason validation')
  const correctedExpense = (await call('POST', `/expenses/${purchaseExpense.id}/correct`, {
    ...purchaseExpense, amount: '125.000', reference_number: 'CHANGED-MANUALLY', reason: 'تصحيح قيمة الفاتورة',
  })).data
  assert(correctedExpense.amount === '125.000', 'Expense correction did not save the new amount')
  assert(correctedExpense.reference_number === purchaseExpense.reference_number, 'Expense correction changed the generated reference')
  await call('POST', `/expenses/${rentExpense.id}/cancel`, { reason: 'إلغاء دفعة اختبار' })
  const expenseList = await call('GET', '/expenses', undefined, { search: 'اختبار', per_page: 100 })
  assert(expenseList.data.some((item) => item.id === rentExpense.id && item.status === 'cancelled'), 'Cancelled expense was not preserved')
  assert(expenseList.summary.total_expenses === '125.000', 'Cancelled expense still affects active totals')
  await expectStatus(422, () => call('POST', '/refunds', {
    patient_id: patient.id,
    payment_id: subscriptionResponse.data.payment.id,
    amount: '10.000',
    method: 'cash',
    reason: 'محاولة استرجاع عامة',
  }), 'Generic subscription refund rejection')

  const secondSubscriptionSession = (await call('POST', '/sessions', {
    patient_id: patient.id, doctor_id: 2, type: 'subscription', subscription_id: subscription.id,
    session_date: new Date().toISOString().slice(0, 10), services: [{ service_id: 2 }],
  })).data.session
  let subscriptionDetails = (await call('GET', `/subscriptions/${subscription.id}`)).data
  assert(subscriptionDetails.sessions_used === 2 && subscriptionDetails.remaining === 1, 'Shared allowance did not consume exactly one session per visit')
  assert(subscriptionDetails.received_amount === '130.000', 'Debt allocation was not included in subscription receipts')
  await call('POST', `/sessions/${secondSubscriptionSession.id}/cancel`, { reason: 'اختبار استعادة رصيد الاشتراك' })
  subscriptionDetails = (await call('GET', `/subscriptions/${subscription.id}`)).data
  assert(subscriptionDetails.sessions_used === 1 && subscriptionDetails.remaining === 2, 'Cancelling a subscription session did not restore exactly one allowance')

  const correction = await call('POST', `/subscriptions/${subscription.id}/correct`, {
    changes: { sessions_count: 4, total_price: '320.000' }, reason: 'اختبار تصحيح عقد الاشتراك',
  })
  assert(correction.data.subscription.sessions_count === 4 && correction.data.subscription.total_price === '320.000', 'Subscription correction did not preserve the requested contract values')

  const cancellationPreview = await call('GET', `/subscriptions/${subscription.id}/cancel-preview`)
  assert(cancellationPreview.data.sessions_used === 1, 'Subscription cancellation preview did not include usage')
  assert(cancellationPreview.data.maximum_refund === '130.000', 'Subscription cancellation preview did not use ledger receipts')
  const cancellation = await call('POST', `/subscriptions/${subscription.id}/cancel`, { reason: 'إلغاء تحقق الواجهة', refund_amount: '50.000', refund_method: 'cash' })
  assert(cancellation.data.subscription.status === 'cancelled', 'Subscription cancellation did not set the terminal status')
  assert(cancellation.data.refund?.amount === '-50.000' && cancellation.data.voided_debt_ids.includes(subscriptionDebt.id), 'Subscription cancellation did not record the explicit refund and void its debt')
  const cancelledDetails = (await call('GET', `/subscriptions/${subscription.id}`)).data
  assert(cancelledDetails.refunded_amount === '50.000' && cancelledDetails.outstanding_amount === '0.000', 'Cancelled subscription financial summary is inconsistent')

  const doctor = (await call('GET', '/doctors/1')).data
  const payoutAmount = Math.min(50, Number(doctor.remaining)).toFixed(3)
  await call('POST', '/doctors/1/payouts', { amount: payoutAmount, date: new Date().toISOString().slice(0, 10), method: 'cash', note: 'Phase 1 verification' })

  for (const report of ['sessions', 'collections', 'debts', 'doctor-dues', 'subscriptions', 'expenses']) {
    const response = await call('GET', `/reports/${report}`, undefined, {})
    assert(Array.isArray(response.data.rows), `Report ${report} did not return rows`)
  }

  const audit = await call('GET', '/audit-log', undefined, { per_page: 100 })
  assert(audit.data.some((entry) => entry.action === 'doctor_paid'), 'Payout was not written to audit log')
  assert(audit.data.some((entry) => entry.action === 'subscription_cancelled'), 'Subscription cancellation was not written to audit log')
  assert(audit.data.some((entry) => entry.action === 'expense_corrected'), 'Expense correction was not written to audit log')
  assert(audit.data.some((entry) => entry.action === 'expense_cancelled'), 'Expense cancellation was not written to audit log')

  process.stdout.write('Mock walkthrough passed: subscriptions, financial flows, purchases and rent, reports, permissions, cancellations, and audit.\n')
} finally {
  await server.close()
}
